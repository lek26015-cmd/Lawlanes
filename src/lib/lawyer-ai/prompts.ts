export function systemPrompt(mode: AiMode, caseContext: string | null, citations: AiCitation[]): string {
    const parts = [BASE, '', MODE[mode]];
    if (caseContext) {
        parts.push('', '=== ข้อมูลคดี (จากระบบจัดการคดีของทนาย) ===', caseContext, '=== จบข้อมูลคดี ===');
    }
    if (citations.length > 0) {
        parts.push('', '=== แหล่งอ้างอิง (ตัวบท/ฎีกาที่ค้นได้จากฐานข้อมูล) ===');
        for (const c of citations) {
            parts.push(`[${c.n}] ${c.title}${c.year ? ` (พ.ศ. ${c.year + 543})` : ''}\n${c.content.slice(0, 2500)}`);
        }
        parts.push('=== จบแหล่งอ้างอิง ===');
    } else {
        parts.push('', '(ไม่พบแหล่งอ้างอิงจากฐานข้อมูลสำหรับคำถามนี้ — อย่าใส่เลขกำกับ [n])');
    }
    return parts.join('\n');
}

/** คำค้นสำหรับ RAG: คำถาม + ชื่อคดี + ต้นเอกสารแนบ (ตรวจสัญญาต้องค้นจากตัวสัญญา ไม่ใช่คำสั่ง "ช่วยตรวจหน่อย") */
export function retrievalQuery(mode: AiMode, question: string, caseTitle: string | null, attachmentText: string): string {
    const bits = [question];
    if (caseTitle) bits.push(caseTitle);
    if (attachmentText && (mode === 'contract' || question.length < 40)) bits.push(attachmentText.slice(0, 1200));
    return bits.join('\n').slice(0, 1500);
}
